import type { NodeId, SimEvent } from '../engine/types.ts';
import { createCluster } from '../swim/cluster.ts';
import type { Update } from '../swim/membership.ts';
import { SwimMetrics } from '../swim/metrics.ts';
import { improvedDetector, type SwimConfig } from '../swim/node.ts';
import { show, summarize, table } from './stats.ts';

/**
 * Failure-detection experiment: classic SWIM against the improved detector,
 * on identical seeds, networks and faults.
 *
 * Each trial: 20 nodes settle on a clean network for 20 s, a fault is applied,
 * false verdicts are counted for 120 s, then one node is really killed and we
 * time how long until every survivor knows.
 */

const SIZE = 20;
const SETTLE = 20_000;
const OBSERVE = 120_000;
const AFTER_KILL = 90_000;
const VICTIM = 'n7';
const SLOW = 'n5';

export interface Fault {
  loss?: number;
  latencyMean?: number;
  /** Make one node 10x slower on all its links. */
  slowNode?: boolean;
}

export interface Outcome {
  /** Death verdicts about nodes that were running, during the observation window. */
  falseDeads: number;
  falseSuspects: number;
  /** ms from the real kill until every survivor had it dead; null if that never happened. */
  detection: number | null;
  /** Slow-node trials: false death verdicts about the slow node, and accusations it made. */
  aboutSlow: number;
  bySlow: number;
}

export function trial(seed: number, swim: Partial<SwimConfig>, fault: Fault): Outcome {
  const sim = createCluster({ seed, size: SIZE, swim });
  const metrics = new SwimMetrics();
  const up = new Set<NodeId>();
  let aboutSlow = 0;
  let bySlow = 0;
  sim.onEvent((e: SimEvent) => {
    metrics.onEvent(e);
    if (e.type === 'up') up.add(e.node);
    else if (e.type === 'down') up.delete(e.node);
    else if (e.type === 'state' && e.kind === 'member') {
      const u = e.data as Update;
      if (u.id === e.node || u.status === 'alive' || !up.has(u.id)) return;
      if (u.id === SLOW && u.status === 'dead') aboutSlow++;
      if (e.node === SLOW) bySlow++;
    }
  });

  sim.runUntil(SETTLE);
  if (fault.loss !== undefined) sim.input({ type: 'network', patch: { loss: fault.loss } });
  if (fault.latencyMean !== undefined) {
    sim.input({ type: 'network', patch: { latencyMean: fault.latencyMean, latencyJitter: fault.latencyMean * 0.375 } });
  }
  if (fault.slowNode) sim.input({ type: 'slow', node: SLOW, factor: 10 });
  sim.runUntil(SETTLE + OBSERVE);
  const { falseDeads, falseSuspects } = metrics;

  sim.input({ type: 'kill', node: VICTIM });
  sim.runUntil(SETTLE + OBSERVE + AFTER_KILL);
  return { falseDeads, falseSuspects, detection: metrics.failures[0].allDead ?? null, aboutSlow, bySlow };
}

export const modes: Record<string, Partial<SwimConfig>> = {
  classic: {},
  ours: improvedDetector,
};

export const ablation: Record<string, Partial<SwimConfig>> = {
  classic: {},
  'phi only': { phi: 1 },
  'self-doubt only': { selfDoubt: 1 },
  'dynamic suspicion only': { dynamicSuspicion: 1 },
  'phi + dynamic (ours)': improvedDetector,
  'ours + self-doubt': { ...improvedDetector, selfDoubt: 1 },
};

function run(seeds: number[], swim: Partial<SwimConfig>, fault: Fault) {
  const outcomes = seeds.map((seed) => trial(seed, swim, fault));
  const detected = outcomes.filter((o) => o.detection !== null).map((o) => o.detection!);
  return {
    falseDeads: summarize(outcomes.map((o) => o.falseDeads)),
    falseSuspects: summarize(outcomes.map((o) => o.falseSuspects)),
    detection: summarize(detected.map((d) => d / 1000)),
    missed: outcomes.length - detected.length,
    aboutSlow: summarize(outcomes.map((o) => o.aboutSlow)),
    bySlow: summarize(outcomes.map((o) => o.bySlow)),
  };
}

function sweep(seeds: number[], label: string, faults: [string, Fault][], variants: Record<string, Partial<SwimConfig>>): string {
  const rows: string[][] = [];
  for (const [name, fault] of faults) {
    for (const [mode, swim] of Object.entries(variants)) {
      const r = run(seeds, swim, fault);
      rows.push([name, mode, show(r.falseDeads), show(r.falseSuspects), show(r.detection, 2), String(r.missed)]);
    }
  }
  return table([label, 'Detector', 'False death verdicts', 'False suspicions', 'Detection time (s)', 'Never detected'], rows);
}

/** Runs the whole experiment and returns a markdown report. */
export function report(seedCount = 20): string {
  const seeds = Array.from({ length: seedCount }, (_, i) => i + 1);
  const out: string[] = [];
  out.push('# Failure detection: classic SWIM vs improved detector');
  out.push(
    `Generated by \`npm run experiment\`. ${SIZE} nodes, ${seedCount} seeds per row, values are mean ± standard deviation across seeds. ` +
      `False verdicts are counted over ${OBSERVE / 1000} s under the fault; then one node is killed and "detection time" is how long until every survivor has it dead. ` +
      'Both detectors face the identical seed, network and faults. "Classic" is fixed ping and suspect timeouts. ' +
      '"Ours" adds phi-accrual ping timeouts and suspicion that shortens with independent confirmations.',
  );

  out.push('## Packet loss');
  out.push(sweep(seeds, 'Loss', [0, 0.1, 0.2, 0.3].map((loss) => [`${loss * 100}%`, { loss }]), modes));

  out.push('## Network latency');
  out.push(sweep(seeds, 'Mean latency', [40, 100, 200, 300].map((ms) => [`${ms} ms`, { latencyMean: ms }]), modes));

  out.push('## One node 10x slower (not dead)');
  const slowRows = Object.entries(modes).map(([mode, swim]) => {
    const r = run(seeds, swim, { slowNode: true });
    return [mode, show(r.aboutSlow), show(r.bySlow), show(r.falseDeads), show(r.detection, 2)];
  });
  out.push(table(['Detector', 'Death verdicts about the slow node', 'Accusations made by the slow node', 'All false death verdicts', 'Detection time (s)'], slowRows));

  out.push('## Trade-off curve at 20% loss');
  out.push('Sweeping the suspect timeout trades detection speed against false verdicts. A better detector sits lower and further left.');
  const curveRows: string[][] = [];
  for (const suspectTimeout of [1000, 2000, 3000, 5000, 8000]) {
    for (const [mode, swim] of Object.entries(modes)) {
      const r = run(seeds, { ...swim, suspectTimeout }, { loss: 0.2 });
      curveRows.push([`${suspectTimeout} ms`, mode, show(r.detection, 2), show(r.falseDeads), String(r.missed)]);
    }
  }
  out.push(table(['Suspect timeout', 'Detector', 'Detection time (s)', 'False death verdicts', 'Never detected'], curveRows));

  out.push('## Which part does the work');
  out.push('Each improvement alone, at 20% loss, at 200 ms latency, and with one slow node.');
  out.push(sweep(seeds, 'Fault', [['20% loss', { loss: 0.2 }], ['200 ms latency', { latencyMean: 200 }], ['one slow node', { slowNode: true }]], ablation));

  return out.join('\n\n') + '\n';
}
